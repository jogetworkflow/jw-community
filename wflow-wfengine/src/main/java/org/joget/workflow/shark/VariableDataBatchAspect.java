    // =========================================================================
    // Fallback helpers
    // =========================================================================

    private <T> void fallbackSaves(List<T> buffer, ThreadLocal<List<T>> tl) {
        tl.remove(); // prevent re-interception
        for (T doObj : buffer) {
            try {
                doObj.getClass().getMethod("save", boolean.class).invoke(doObj, false);
            } catch (Exception e) {
                LogUtil.error(LOG_CLASS, e, "Fallback individual save also failed for " + doObj.getClass().getSimpleName());
            }
        }
    }

    // =========================================================================
    // PreparedStatement helpers
    // =========================================================================

    private void setBytes(PreparedStatement ps, int idx, byte[] val) throws SQLException {
        if (val != null) ps.setBytes(idx, val);
        else ps.setNull(idx, java.sql.Types.BINARY);
    }

    private void setString(PreparedStatement ps, int idx, String val) throws SQLException {
        if (val != null) ps.setString(idx, val);
        else ps.setNull(idx, java.sql.Types.VARCHAR);
    }

    private void setDouble(PreparedStatement ps, int idx, short type, int dblType, double val) throws SQLException {
        if (type == dblType) ps.setDouble(idx, val);
        else ps.setNull(idx, java.sql.Types.DOUBLE);
    }

    private void setLong(PreparedStatement ps, int idx, short type, int longType, long val) throws SQLException {
        if (type == longType) ps.setLong(idx, val);
        else ps.setNull(idx, java.sql.Types.BIGINT);
    }

    private void setTimestamp(PreparedStatement ps, int idx, Timestamp val) throws SQLException {
        if (val != null) ps.setTimestamp(idx, val);
        else ps.setNull(idx, java.sql.Types.TIMESTAMP);
    }

    private void setBoolean(PreparedStatement ps, int idx, short type, int boolType, boolean val) throws SQLException {
        if (type == boolType) ps.setBoolean(idx, val);
        else ps.setNull(idx, java.sql.Types.BOOLEAN);
    }

    private void closeQuietly(PreparedStatement ps, Connection conn, DataSource ds) {
        if (ps != null) { try { ps.close(); } catch (SQLException ignored) {} }
        if (conn != null) DataSourceUtils.releaseConnection(conn, ds);
    }

    // =========================================================================
    // Reflection helpers
    // =========================================================================

    private static Object readField(Object target, String fieldName) throws Exception {
        Field field = findDeclaredField(target.getClass(), fieldName);
        field.setAccessible(true);
        return field.get(target);
    }

    private static void writeField(Object target, String fieldName, Object value) throws Exception {
        Field field = findDeclaredField(target.getClass(), fieldName);
        field.setAccessible(true);
        field.set(target, value);
    }

    private static Field findDeclaredField(Class<?> clazz, String fieldName) throws NoSuchFieldException {
        for (Class<?> c = clazz; c != null; c = c.getSuperclass()) {
            try { return c.getDeclaredField(fieldName); } catch (NoSuchFieldException ignored) {}
        }
        throw new NoSuchFieldException(fieldName);
    }

    private static java.lang.reflect.Method findDeclaredMethod(Class<?> clazz, String methodName, Class<?>... paramTypes) throws NoSuchMethodException {
        for (Class<?> c = clazz; c != null; c = c.getSuperclass()) {
            try { return c.getDeclaredMethod(methodName, paramTypes); } catch (NoSuchMethodException ignored) {}
        }
        throw new NoSuchMethodException(methodName);
    }
