    // Pointcut 7: cache getPersistedActivityVariableObject (scalar)
    // =========================================================================

    @Around("execution(* org.enhydra.shark.instancepersistence.DODSPersistentManager.getPersistedActivityVariableObject(..))")
    public Object aroundGetPersistedActivityVariableObject(ProceedingJoinPoint pjp) throws Throwable {
        Map<String, Map<String, List<ActivityDataDO>>> dataCache = activityDataCache.get();
        if (dataCache == null) return pjp.proceed();
        Object[] args = pjp.getArgs();
        if (args == null || args.length < 2 || !(args[0] instanceof String) || !(args[1] instanceof String))
            return pjp.proceed();
        String activityId = (String) args[0];
        String varDefId   = (String) args[1];
        if (!dataCache.containsKey(activityId)) bulkLoadActivityData(activityId, dataCache);
        Map<String, List<ActivityDataDO>> varMap = dataCache.get(activityId);
        if (varMap == null) return pjp.proceed();
        List<ActivityDataDO> list = varMap.get(varDefId);
        return (list != null && !list.isEmpty()) ? list.get(0) : null;
    }

