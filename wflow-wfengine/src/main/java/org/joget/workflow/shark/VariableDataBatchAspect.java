    // Pointcut 5: cache getPersistedActivityObject within persistActivityContext
    // =========================================================================

    @Around("execution(* org.enhydra.shark.instancepersistence.DODSPersistentManager.getPersistedActivityObject(..))")
    public Object aroundGetPersistedActivityObject(ProceedingJoinPoint pjp) throws Throwable {
        Map<String, Object> cache = activityCache.get();
        if (cache == null) return pjp.proceed();
        Object[] args = pjp.getArgs();
        if (args == null || args.length == 0 || !(args[0] instanceof String)) return pjp.proceed();
        String id = (String) args[0];
        if (cache.containsKey(id)) {
            LogUtil.debug(LOG_CLASS, "Cache hit SHKActivities id=" + id);
            return cache.get(id);
        }
        Object result = pjp.proceed();
        cache.put(id, result);
        return result;
    }

