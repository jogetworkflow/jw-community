    // =========================================================================
    // Pointcut 11: log activitiesProcessContext before setActivityVariables
    // =========================================================================

    @Around("execution(* org.enhydra.shark.WfActivityImpl.setActivityVariables(..))")
    public Object aroundSetActivityVariables(ProceedingJoinPoint pjp) throws Throwable  {
        Object target = pjp.getThis();
        Object result = pjp.proceed();

        try {
            @SuppressWarnings("unchecked")
            Map<String, Object> context = (Map<String, Object>) readField(target, "activitiesProcessContext");
            if (context == null) {
                LogUtil.debug(LOG_CLASS, "setActivityVariables: activitiesProcessContext is null");
            } else {
                WMSessionHandle shandle = (WMSessionHandle) pjp.getArgs()[0];
                if (shandle != null) {
                    java.lang.reflect.Method getDefMethod = findDeclaredMethod(target.getClass(), "getProcessDefinition",
                            org.enhydra.shark.api.client.wfmc.wapi.WMSessionHandle.class);
                    getDefMethod.setAccessible(true);
                    Object wp = getDefMethod.invoke(target, shandle);
                    if (wp != null) {
                        @SuppressWarnings("unchecked")
                        Map<String, Object> allVars = (Map<String, Object>)
                                wp.getClass().getMethod("getAllVariables").invoke(wp);
                        if (allVars != null) {
                            int added = 0;
                            for (String varId : allVars.keySet()) {
                                if (!context.containsKey(varId)) {
                                    context.put(varId, null);
                                    added++;
                                }
                            }
                            if (added > 0) {
                                LogUtil.debug(LOG_CLASS, "setActivityVariables: added " + added + " missing variable(s) to activitiesProcessContext");
                            }
                        }
                    }
                }
            }
        } catch (Exception e) {
            LogUtil.warn(LOG_CLASS, "setActivityVariables: could not read activitiesProcessContext — " + e.getMessage());
        }

        return result;
    }

    // =========================================================================
    // Bulk pre-fetch helpers
    // =========================================================================

    /**
     * Pre-fetch ALL SHKActivityData rows for the given activity with a single query.
     * Falls back to an ActivityQuery lookup when the ActivityDO isn't in activityCache yet.
     */
    private void bulkLoadActivityData(String activityId,
            Map<String, Map<String, List<ActivityDataDO>>> dataCache) {
        Map<String, List<ActivityDataDO>> varMap = new HashMap<>();
        dataCache.put(activityId, varMap); // register immediately to block re-entry
        try {
            Map<String, Object> aCache = activityCache.get();
            Object actObj = (aCache != null) ? aCache.get(activityId) : null;
            ActivityDO actDO;
            if (actObj instanceof ActivityDO) {
                actDO = (ActivityDO) actObj;
            } else {
                ActivityQuery aq = new ActivityQuery();
                aq.setQueryId(activityId);
                ActivityDO[] acts = aq.getDOArray();
                if (acts == null || acts.length == 0) {
                    LogUtil.debug(LOG_CLASS, "Activity not found in DB for id=" + activityId + " — skipping bulk pre-fetch");
                    return;
                }
                actDO = acts[0];
                if (aCache != null) aCache.put(activityId, actDO);
            }
            ActivityDataQuery q = new ActivityDataQuery();
            q.setQueryActivity(actDO);
            ActivityDataDO[] all = q.getDOArray();
            for (ActivityDataDO row : all) {
                String vid = row.getVariableDefinitionId();
                varMap.computeIfAbsent(vid, k -> new ArrayList<>()).add(row);
            }
            LogUtil.debug(LOG_CLASS, "Bulk pre-fetched " + all.length + " SHKActivityData rows for activity=" + activityId);
        } catch (Exception e) {
            LogUtil.error(LOG_CLASS, e, "Bulk pre-fetch of SHKActivityData failed for activity=" + activityId);
            dataCache.remove(activityId);
        }
    }

    /**
     * Pre-fetch ALL SHKProcessData rows for the given process with a single query.
     * Falls back to a ProcessQuery lookup when the ProcessDO isn't in processCache yet.
     */
    private void bulkLoadProcessData(String processId,
            Map<String, Map<String, List<ProcessDataDO>>> dataCache) {
        Map<String, List<ProcessDataDO>> varMap = new HashMap<>();
        dataCache.put(processId, varMap); // register immediately to block re-entry
        try {
            Map<String, Object> pCache = processCache.get();
            Object procObj = (pCache != null) ? pCache.get(processId) : null;
            ProcessDO procDO;
            if (procObj instanceof ProcessDO) {
                procDO = (ProcessDO) procObj;
            } else {
                ProcessQuery pq = new ProcessQuery();
                pq.setQueryId(processId);
                ProcessDO[] procs = pq.getDOArray();
                if (procs == null || procs.length == 0) {
                    LogUtil.debug(LOG_CLASS, "Process not found in DB for id=" + processId + " — skipping bulk pre-fetch");
                    return;
                }
                procDO = procs[0];
                if (pCache != null) pCache.put(processId, procDO);
            }
            ProcessDataQuery q = new ProcessDataQuery();
            q.setQueryProcess(procDO);
            ProcessDataDO[] all = q.getDOArray();
            for (ProcessDataDO row : all) {
                String vid = row.getVariableDefinitionId();
                varMap.computeIfAbsent(vid, k -> new ArrayList<>()).add(row);
            }
            LogUtil.debug(LOG_CLASS, "Bulk pre-fetched " + all.length + " SHKProcessData rows for process=" + processId);
        } catch (Exception e) {
            LogUtil.error(LOG_CLASS, e, "Bulk pre-fetch of SHKProcessData failed for process=" + processId);
            dataCache.remove(processId);
        }
    }

    // =========================================================================
    // Changed-value filter: skip unchanged activity variables before persist
    // =========================================================================

    /**
     * Before persistActivityContext proceeds, compare each variable in
     * variableIdsToPersist against the already-persisted VariableValueVCHAR.
     * Variables whose value has not changed are removed from the set so the
     * engine never issues an INSERT/UPDATE for them.
     *
     * Only applied for activity context — process context is left untouched.
     */
    @SuppressWarnings("unchecked")
    private void filterUnchangedActivityVariables(ProceedingJoinPoint pjp) {
        try {
            Object target = pjp.getThis();

            // Get activity ID and the mutable set of variable IDs to persist
            String activityId = (String) readField(target, "key");
            Set<String> varIds = (Set<String>) readField(target, "variableIdsToPersist");
            if (varIds == null || varIds.isEmpty()) return;

            // Pre-load the activity data cache so we can compare without extra queries
            Map<String, Map<String, List<ActivityDataDO>>> dataCache = activityDataCache.get();
            if (!dataCache.containsKey(activityId)) {
                bulkLoadActivityData(activityId, dataCache);
            }
            Map<String, List<ActivityDataDO>> varMap = dataCache.get(activityId);

            // Read the current in-memory context map directly from the field
            Map<String, Object> currentContext = (Map<String, Object>) readField(target, "activitiesProcessContext");
            if (currentContext == null) return;

            // Remove variables whose VCHAR value is identical to what is already in DB
            Set<String> toRemove = new HashSet<String>();
            for (String varId : varIds) {
                Object currentVal = currentContext.get(varId);
                
                List<ActivityDataDO> existingList = varMap.get(varId);
                if (existingList == null || existingList.isEmpty()) {
                    // No persisted row yet — only INSERT if the variable has a value
                    if (currentVal == null ||  String.valueOf(currentVal).isEmpty()) {
                        toRemove.add(varId);
                    }
                    continue;
                }
                String persistedVchar = existingList.get(0).getVariableValueVCHAR();
                String currentVchar = (currentVal != null) ? String.valueOf(currentVal) : null;
                if (isVcharEqual(persistedVchar, currentVchar)) {
                    toRemove.add(varId);
                }
            }

            if (!toRemove.isEmpty()) {
                varIds.removeAll(toRemove);
                LogUtil.debug(LOG_CLASS, "Skipped " + toRemove.size() + " unchanged variable(s) for activity=" + activityId + ": " + toRemove);
            }
        } catch (Exception e) {
            LogUtil.warn(LOG_CLASS, "filterUnchangedActivityVariables failed — proceeding without filter: " + e.getMessage());
        }
    }

    private boolean isVcharEqual(String a, String b) {
        if (a == null && b == null) return true;
        if (a == null || b == null) return false;
        return a.equals(b);
    }

    // =========================================================================
    // Flush: batch INSERT SHKActivityData
    // =========================================================================

    private void flushBatch() {
        List<ActivityDataDO> buffer = insertBuffer.get();
        if (buffer == null || buffer.isEmpty()) return;
        DataSource ds = (DataSource) WorkflowUtil.getApplicationContext().getBean("setupDataSource");
        Connection conn = null;
        PreparedStatement ps = null;
        int batchSize = buffer.size();
        try {
            conn = DataSourceUtils.getConnection(ds);
            String sql = "INSERT INTO SHKActivityData"
                    + " (Activity, VariableDefinitionId, VariableType,"
                    + " VariableValue, VariableValueXML, VariableValueVCHAR,"
                    + " VariableValueDBL, VariableValueLONG, VariableValueDATE,"
                    + " VariableValueBOOL, IsResult, OrdNo, CNT, oid, version)"
                    + " VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)";
            ps = conn.prepareStatement(sql);
            for (ActivityDataDO doObj : buffer) {
                populateActivityInsertStatement(ps, doObj);
                ps.addBatch();
            }
            ps.executeBatch();
            for (ActivityDataDO doObj : buffer) {
                writeField(doObj, "persistent", true);
                writeField(doObj, "dirty", false);
            }
            LogUtil.debug(LOG_CLASS, "Batch inserted " + batchSize + " SHKActivityData rows");
        } catch (Exception e) {
            LogUtil.error(LOG_CLASS, e, "Batch INSERT SHKActivityData failed (" + batchSize + " rows) — falling back");
            fallbackSaves(buffer, insertBuffer);
        } finally {
            closeQuietly(ps, conn, ds);
        }
    }

    private void populateActivityInsertStatement(PreparedStatement ps, ActivityDataDO doObj) throws Exception {
        ps.setBigDecimal(1, doObj.oid_getActivity());
        ps.setString(2, doObj.getVariableDefinitionId());
        ps.setShort(3, doObj.getVariableType());
        setBytes(ps, 4, doObj.getVariableValue());
        setString(ps, 5, doObj.getStringVariableValueXML());
        setString(ps, 6, doObj.getVariableValueVCHAR());
        setDouble(ps, 7, doObj.getVariableType(), 2, doObj.getVariableValueDBL());
        setLong(ps, 8, doObj.getVariableType(), 1, doObj.getVariableValueLONG());
        setTimestamp(ps, 9, doObj.getVariableValueDATE());
        setBoolean(ps, 10, doObj.getVariableType(), 0, doObj.getVariableValueBOOL());
        ps.setBoolean(11, doObj.getIsResult());
        ps.setInt(12, doObj.getOrdNo());
        ps.setBigDecimal(13, doObj.getCNT());
        ps.setBigDecimal(14, doObj.get_OId().toBigDecimal());
        ps.setInt(15, 0);
    }

    // =========================================================================
    // Flush: batch UPDATE SHKActivityData
    // =========================================================================

    private void flushUpdateBatch() {
        List<ActivityDataDO> buffer = updateBuffer.get();
        if (buffer == null || buffer.isEmpty()) return;
        DataSource ds = (DataSource) WorkflowUtil.getApplicationContext().getBean("setupDataSource");
        Connection conn = null;
        PreparedStatement ps = null;
        int batchSize = buffer.size();
        try {
            conn = DataSourceUtils.getConnection(ds);
            String sql = "UPDATE SHKActivityData SET"
                    + " version=?, VariableValue=?, VariableValueXML=?, VariableValueVCHAR=?,"
                    + " VariableValueDBL=?, VariableValueLONG=?, VariableValueDATE=?,"
                    + " VariableValueBOOL=?, IsResult=?"
                    + " WHERE oid=? AND version=?";
            ps = conn.prepareStatement(sql);
            for (ActivityDataDO doObj : buffer) {
                populateActivityUpdateStatement(ps, doObj);
                ps.addBatch();
            }
            ps.executeBatch();
            LogUtil.debug(LOG_CLASS, "Batch updated " + batchSize + " SHKActivityData rows");
        } catch (Exception e) {
            LogUtil.error(LOG_CLASS, e, "Batch UPDATE SHKActivityData failed (" + batchSize + " rows) — falling back");
            fallbackSaves(buffer, updateBuffer);
        } finally {
            closeQuietly(ps, conn, ds);
        }
    }

    private void populateActivityUpdateStatement(PreparedStatement ps, ActivityDataDO doObj) throws Exception {
        ps.setInt(1, doObj.get_NewVersion());
        setBytes(ps, 2, doObj.getVariableValue());
        setString(ps, 3, doObj.getStringVariableValueXML());
        setString(ps, 4, doObj.getVariableValueVCHAR());
        setDouble(ps, 5, doObj.getVariableType(), 2, doObj.getVariableValueDBL());
        setLong(ps, 6, doObj.getVariableType(), 1, doObj.getVariableValueLONG());
        setTimestamp(ps, 7, doObj.getVariableValueDATE());
        setBoolean(ps, 8, doObj.getVariableType(), 0, doObj.getVariableValueBOOL());
        ps.setBoolean(9, doObj.getIsResult());
        ps.setBigDecimal(10, doObj.get_OId().toBigDecimal());
        ps.setInt(11, doObj.get_Version());
    }

    // =========================================================================
    // Flush: batch INSERT SHKProcessData
    // =========================================================================

    private void flushProcessDataInsertBatch() {
        List<ProcessDataDO> buffer = processDataInsertBuffer.get();
        if (buffer == null || buffer.isEmpty()) return;
        DataSource ds = (DataSource) WorkflowUtil.getApplicationContext().getBean("setupDataSource");
        Connection conn = null;
        PreparedStatement ps = null;
        int batchSize = buffer.size();
        try {
            conn = DataSourceUtils.getConnection(ds);
            String sql = "INSERT INTO SHKProcessData"
                    + " (Process, VariableDefinitionId, VariableType,"
                    + " VariableValue, VariableValueXML, VariableValueVCHAR,"
                    + " VariableValueDBL, VariableValueLONG, VariableValueDATE,"
                    + " VariableValueBOOL, OrdNo, CNT, oid, version)"
                    + " VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)";
            ps = conn.prepareStatement(sql);
            for (ProcessDataDO doObj : buffer) {
                populateProcessDataInsertStatement(ps, doObj);
                ps.addBatch();
            }
            ps.executeBatch();
            for (ProcessDataDO doObj : buffer) {
                writeField(doObj, "persistent", true);
                writeField(doObj, "dirty", false);
            }
            LogUtil.debug(LOG_CLASS, "Batch inserted " + batchSize + " SHKProcessData rows");
        } catch (Exception e) {
            LogUtil.error(LOG_CLASS, e, "Batch INSERT SHKProcessData failed (" + batchSize + " rows) — falling back");
            fallbackSaves(buffer, processDataInsertBuffer);
        } finally {
            closeQuietly(ps, conn, ds);
        }
    }

    private void populateProcessDataInsertStatement(PreparedStatement ps, ProcessDataDO doObj) throws Exception {
        ps.setBigDecimal(1, doObj.oid_getProcess());
        ps.setString(2, doObj.getVariableDefinitionId());
        ps.setShort(3, doObj.getVariableType());
        setBytes(ps, 4, doObj.getVariableValue());
        setString(ps, 5, doObj.getStringVariableValueXML());
        setString(ps, 6, doObj.getVariableValueVCHAR());
        setDouble(ps, 7, doObj.getVariableType(), 2, doObj.getVariableValueDBL());
        setLong(ps, 8, doObj.getVariableType(), 1, doObj.getVariableValueLONG());
        setTimestamp(ps, 9, doObj.getVariableValueDATE());
        setBoolean(ps, 10, doObj.getVariableType(), 0, doObj.getVariableValueBOOL());
        ps.setInt(11, doObj.getOrdNo());
        ps.setBigDecimal(12, doObj.getCNT());
        ps.setBigDecimal(13, doObj.get_OId().toBigDecimal());
        ps.setInt(14, 0);
    }

